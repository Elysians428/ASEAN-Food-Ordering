    public void tampilkanMenuBerdasarkanUkuran(String ukuran) {
       String[] judulKolom = {"ID Makanan", "Nama Makanan", "Asal Negara", "Harga"};
        DefaultTableModel model = new DefaultTableModel(null, judulKolom) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        // MENGGUNAKAN jTable1 SESUAI DESAIN KAMU
        jTable1.setModel(model);
        
        try {
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/db_restoran_asean", "root", "");
            String sql = "SELECT m.id_makanan, m.nama_makanan, m.asal_negara, v.harga " +
                         "FROM makanan m JOIN varian_porsi v ON m.id_makanan = v.id_makanan " +
                         "WHERE v.ukuran = ? AND v.bisa_dine_in = 1";
            java.sql.PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, ukuran);
            java.sql.ResultSet rs = ps.executeQuery();
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id_makanan"),
                    rs.getString("nama_makanan"),
                    rs.getString("asal_negara"),
                    rs.getDouble("harga")
                });
            }
            rs.close();
            ps.close();
            conn.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat daftar menu Dine In: " + e.getMessage());
        }
    }

