    private void btnTambahkanKeKeranjangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahkanKeKeranjangActionPerformed
        // TODO add your handling code here:
       int barisTerpilih = jTable1.getSelectedRow(); // Menggunakan jTable1
        if (barisTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Silakan pilih makanan dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idMakanan = Integer.parseInt(jTable1.getValueAt(barisTerpilih, 0).toString());
        String namaMakanan = jTable1.getValueAt(barisTerpilih, 1).toString();
        String ukuranPorsi = jComboBox1.getSelectedItem().toString();
        String strJumlah = jTextField2.getText().trim(); // Kolom Jumlah Porsi
        
        if (strJumlah.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Jumlah porsi harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int jumlahBeli = Integer.parseInt(strJumlah);
            if (jumlahBeli <= 0) {
                JOptionPane.showMessageDialog(this, "Jumlah porsi harus lebih dari 0!");
                return;
            }

            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/db_restoran_asean", "root", "");
            String sqlCek = "SELECT id_varian, harga, stok FROM varian_porsi WHERE id_makanan = ? AND ukuran = ?";
            java.sql.PreparedStatement psCek = conn.prepareStatement(sqlCek);
            psCek.setInt(1, idMakanan);
            psCek.setString(2, ukuranPorsi);
            java.sql.ResultSet rsCek = psCek.executeQuery();

            if (rsCek.next()) {
                int idVarian = rsCek.getInt("id_varian");
                double hargaSatuan = rsCek.getDouble("harga");
                int stokTersedia = rsCek.getInt("stok");

                if (jumlahBeli > stokTersedia) {
                    JOptionPane.showMessageDialog(this, "Stok tidak mencukupi! Sisa stok hanya: " + stokTersedia + " porsi.");
                    conn.close();
                    return;
                }

                double subTotal = hargaSatuan * jumlahBeli;

                // Disimpan langsung ke memori internal program
                listIdVarian.add(idVarian);
                listNamaMenuBelanja.add(namaMakanan + " (" + ukuranPorsi + ")");
                listJumlahBeli.add(jumlahBeli);
                listSubTotalHarga.add(subTotal);

                // Notifikasi kecil kalau item berhasil disimpan ke memori keranjang
                JOptionPane.showMessageDialog(this, namaMakanan + " (" + ukuranPorsi + ") sebanyak " + jumlahBeli + " porsi berhasil ditambahkan!");

                // Reset field jumlah porsi agar siap input item berikutnya
                jTextField2.setText("");
                jTable1.clearSelection();
            }
            rsCek.close();
            psCek.close();
            conn.close();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Jumlah porsi wajib berupa angka bulat!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnTambahkanKeKeranjangActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String namaPelanggan = jTextField1.getText().trim(); 
        if (namaPelanggan.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Pelanggan wajib diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (listIdVarian.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Keranjang belanja kosong! Silakan tambah menu terlebih dahulu.", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        StringBuilder struk = new StringBuilder();
        struk.append("============== STRUK MAKAN DI SINI ==============\n");
        struk.append("Nama Pelanggan  : ").append(namaPelanggan).append("\n");
        struk.append("-------------------------------------------\n");
        struk.append("Daftar Menu Pesanan:\n");

        double totalAkhir = 0;
        for (int i = 0; i < listIdVarian.size(); i++) {
            struk.append("- ").append(listNamaMenuBelanja.get(i))
                 .append(" x").append(listJumlahBeli.get(i))
                 .append(" = Rp ").append(listSubTotalHarga.get(i)).append("\n");
            totalAkhir += listSubTotalHarga.get(i);
        }

        struk.append("-------------------------------------------\n");
        struk.append("TOTAL PEMBAYARAN : Rp ").append(totalAkhir).append("\n\n");
        struk.append("Apakah semua pesanan Makan Di Sini sudah benar?");

        int konfirmasi = JOptionPane.showConfirmDialog(this, struk.toString(), "Konfirmasi Pembayaran", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try (java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/db_restoran_asean", "root", "")) {
                conn.setAutoCommit(false); 
                
                String sqlUpdateStok = "UPDATE varian_porsi SET stok = stok - ? WHERE id_varian = ?";
                // TIPE PESANAN DISET JADI 'DINEIN' DAN NO_MEJA DIAWALI DENGAN 0 / DEFAULT SEBELUM DI-BOOKING KASIR
            String sqlInsertPesanan = "INSERT INTO pesanan (nama_pelanggan, tipe_pesanan, no_meja, id_varian, total_harga_rp) VALUES (?, 'DINE', NULL, ?, ?)";
                try (java.sql.PreparedStatement psUpdate = conn.prepareStatement(sqlUpdateStok);
                     java.sql.PreparedStatement psInsert = conn.prepareStatement(sqlInsertPesanan)) {
                    
                    for (int i = 0; i < listIdVarian.size(); i++) {
                        psUpdate.setInt(1, listJumlahBeli.get(i));
                        psUpdate.setInt(2, listIdVarian.get(i));
                        psUpdate.addBatch();
                        
                        psInsert.setString(1, namaPelanggan);
                        psInsert.setInt(2, listIdVarian.get(i));
                        psInsert.setInt(3, listSubTotalHarga.get(i).intValue());
                        psInsert.addBatch();
                    }
                    
                    psUpdate.executeBatch();
                    psInsert.executeBatch();
                    conn.commit(); 
                    
                    JOptionPane.showMessageDialog(this, "Sukses! Pesanan Makan Di Sini berhasil disimpan.");
                    
                    jTextField1.setText("");
                    jTextField2.setText("");
                    listIdVarian.clear();
                    listNamaMenuBelanja.clear();
                    listJumlahBeli.clear();
                    listSubTotalHarga.clear();
                    keranjangListModel.clear();
                    
                    
                    tampilkanMenuBerdasarkanUkuran(jComboBox1.getSelectedItem().toString());
                    
                } catch (java.sql.SQLException ex) {
                    conn.rollback();
                    throw ex;
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal memproses ke database: " + e.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

